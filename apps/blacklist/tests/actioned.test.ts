import assert from 'node:assert/strict';
import {readFileSync,readdirSync} from 'node:fs';
import {POST} from '../app/api/actioned/route';
import {GET} from '../app/api/workspace/route';
import {sqlite,signIn} from './actioned-server';
import {actionExpiresAt,isRecentlyActioned,isInInbox,ACTIONED_RETENTION_MS} from '../app/lib/actioned';
import type {ArticleAction} from '../app/lib/types';
for(const migration of readdirSync('drizzle').filter(n=>n.endsWith('.sql')).sort())sqlite.exec(readFileSync('drizzle/'+migration,'utf8'));
const now=Date.now(),stamp=new Date(now).toISOString();
const row={articleId:'old',actionedAt:stamp,actionedBy:'Analyst A',updatedAt:stamp,version:1};
assert.equal(actionExpiresAt(row),now+ACTIONED_RETENTION_MS);
assert.equal(isRecentlyActioned(row,now+ACTIONED_RETENTION_MS-1),true);
assert.equal(isRecentlyActioned(row,now+ACTIONED_RETENTION_MS),false,'Expire exactly at seven days');
assert.equal(isInInbox(row),false,'Expiry must not resurrect previously handled intelligence');
assert.equal(isInInbox({...row,actionedAt:null}),true,'Undo restores inbox eligibility');
assert.equal(actionExpiresAt({...row,actionedAt:'invalid'}),null);
assert.equal(isRecentlyActioned(undefined,now),false);
const insert=sqlite.prepare('insert into articles(id,url,payload,published_at,kind) values(?,?,?,?,?)');
insert.run('old','https://example.org/old',JSON.stringify({id:'old',publishedAt:'2025-01-01T00:00:00Z'}),'2025-01-01T00:00:00Z','research');
sqlite.prepare('insert into hunts(id,article_id,updated_at,updated_by) values(?,?,?,?)').run('legacy','old',stamp,'Analyst A');
sqlite.prepare('insert into notes(id,hunt_id,actor,body,created_at) values(?,?,?,?,?)').run('note','legacy','Analyst A','Preserved evidence reference',stamp);
const post=(body:unknown,origin='https://test.example')=>POST(new Request('https://test.example/api/actioned',{method:'POST',headers:{'content-type':'application/json',origin},body:JSON.stringify(body)}));
assert.equal((await post({articleId:'old',actioned:true,expectedVersion:0})).status,401);
signIn({userId:'analyst-a',displayName:'Analyst A'});
assert.equal((await post({articleId:'old',actioned:true,expectedVersion:0},'https://untrusted.example')).status,403);
assert.equal((await post({articleId:'old',actioned:'yes',expectedVersion:0})).status,400);
assert.equal((await post({articleId:'old',actioned:true,expectedVersion:-1})).status,400);
assert.equal((await post({articleId:'old',actioned:true,expectedVersion:0,actionedAt:'2020-01-01'})).status,400,'Client cannot select the clock');
assert.equal((await post({articleId:'missing',actioned:true,expectedVersion:0})).status,404);
const racing=await Promise.all([post({articleId:'old',actioned:true,expectedVersion:0}),post({articleId:'old',actioned:true,expectedVersion:0})]);
assert.deepEqual(racing.map(r=>r.status).sort(),[200,409],'Concurrent initial marks have one winner');
const initial=((await racing.find(r=>r.status===200)!.json()) as any).action as ArticleAction;
assert.equal(initial.actionedBy,'Analyst A');assert.equal(initial.version,1);
const duplicate=await post({articleId:'old',actioned:true,expectedVersion:1});
assert.equal(duplicate.status,200);assert.deepEqual(((await duplicate.json()) as any).action,initial,'Repeated mark preserves timestamp and version');
// Make the marked report older than the ordinary 700-report query window.
for(let i=0;i<701;i++)insert.run('new-'+i,'https://example.org/'+i,JSON.stringify({id:'new-'+i,publishedAt:stamp}),stamp,'feed');
let workspace:any=await (await GET(new Request('https://test.example/api/workspace'))).json();
assert.ok(workspace.articles.some((a:any)=>a.id==='old'),'Recently marked older report stays in Actioned regardless of publication limit');
assert.equal(workspace.actions.length,1);assert.equal(workspace.notes[0].body,'Preserved evidence reference');
const expired=new Date(now-ACTIONED_RETENTION_MS-1000).toISOString();
sqlite.prepare('update article_actions set actioned_at=? where article_id=?').run(expired,'old');
workspace=await (await GET(new Request('https://test.example/api/workspace?brief=old'))).json();
assert.ok(workspace.articles.some((a:any)=>a.id==='old'),'Expired briefing remains available by direct link');
assert.equal(isRecentlyActioned(workspace.actions[0],Date.now()),false);assert.equal(isInInbox(workspace.actions[0]),false);
signIn({userId:'analyst-b',displayName:'Analyst B'});
assert.equal((await post({articleId:'old',actioned:false,expectedVersion:0})).status,409);
const undone=await post({articleId:'old',actioned:false,expectedVersion:1});
assert.equal(undone.status,200);assert.equal(((await undone.json()) as any).action.actionedAt,null);
const remarked=await post({articleId:'old',actioned:true,expectedVersion:2});
const shared=((await remarked.json()) as any).action;
assert.equal(shared.actionedBy,'Analyst B');assert.equal(shared.version,3);assert.equal(isRecentlyActioned(shared,Date.now()),true);
assert.equal(sqlite.prepare('select count(*) as n from article_actions').get()!.n,1,'One durable marker per report');
assert.equal(sqlite.prepare('select body from notes where id=?').get('note')!.body,'Preserved evidence reference');
console.log('PASS: action/undo persistence, shared analyst state, seven-day boundary, idempotency, concurrent marks, stale edit rejection, origin/auth/input validation, older report retention, direct links and legacy data preservation.');
sqlite.close();
